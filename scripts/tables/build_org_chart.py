"""CF-109 — generate diagrams/org_chart.mmd (Mermaid) from data/tables/directory.csv, so they always match.

FICTITIOUS roles are drawn with a dashed border. Run: .venv/Scripts/python scripts/tables/build_org_chart.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    rows = list(csv.DictReader(open(ROOT / "data/tables/directory.csv", encoding="utf-8")))
    node = lambda rid: rid.replace("-", "_")
    out = ["%% Generated by scripts/tables/build_org_chart.py from data/tables/directory.csv — do not edit by hand",
           "flowchart TD"]
    for r in rows:
        out.append(f'    {node(r["role_id"])}["{r["role_title"]}<br/><small>{r["role_id"]}</small>"]')
    for r in rows:
        if r["reports_to"]:
            out.append(f'    {node(r["reports_to"])} --> {node(r["role_id"])}')
    fict = [node(r["role_id"]) for r in rows if r["source"].startswith("FICTITIOUS")]
    out += ["    classDef fictitious stroke-dasharray: 5 5,fill:#fff7e6,stroke:#c77700",
            f"    class {','.join(fict)} fictitious",
            "%% Dashed boxes = FICTITIOUS roles (invented, esprit.example e-mails)"]
    (ROOT / "diagrams").mkdir(exist_ok=True)
    (ROOT / "diagrams/org_chart.mmd").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"org_chart.mmd: {len(rows)} nodes, {sum(1 for r in rows if r['reports_to'])} edges, {len(fict)} FICTITIOUS")


if __name__ == "__main__":
    main()
