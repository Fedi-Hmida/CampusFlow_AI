"""CF-018 / CF-019 — generate the n8n tool workflows from workflows/lib/lookup.js (the code the node tests cover).

  workflows/10_tool_lookup_exam.json     Execute Workflow Trigger → read exam_calendar.csv → lookupExam
  workflows/11_tool_lookup_contact.json  … directory.csv → lookupContact
  workflows/12_tool_lookup_request.json  … request_catalogue.csv + directory.csv → lookupRequest
  workflows/02_wf2_tables_check.json     Manual trigger → read the 3 tables → schema / id / count report (WF-2)
  workflows/03t_tools_test.json          Webhook → Execute Workflow (id from the body) — integration test only,
                                         published for the test run, then unpublished (n8n is public through ngrok)
Tools are PUBLISHED (n8n 2.x only runs published sub-workflows; an Execute Workflow Trigger has no public URL).
Tools read the CSV at every call, so the tables are always current: "refresh" = WF-2 report + run_all validator.
CSV parsing keeps empty cells (includeEmptyCells): otherwise n8n drops the key and a missing room would vanish
instead of becoming null (found by WF-2 on 26 Oct).
Input of a tool: {"query": {...}} (or the query fields directly). Output: one item, the lookup result.
Run: .venv/Scripts/python scripts/workflows/build_tools.py
"""
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
W = ROOT / "workflows"
LIB = (W / "lib/lookup.js").read_text(encoding="utf-8")
NS = uuid.UUID("3d0c8a52-1f7e-4b0a-8f6e-2b9d6c1a7e44")


def nid(wf: str, name: str) -> str:
    return str(uuid.uuid5(NS, f"{wf}/{name}"))


def node(wf, name, type_, version, pos, params, **extra):
    return {"id": nid(wf, name), "name": name, "type": type_, "typeVersion": version, "position": pos, "parameters": params, **extra}


def chain(names: list[str]) -> dict:
    return {a: {"main": [[{"node": b, "type": "main", "index": 0}]]} for a, b in zip(names, names[1:])}


def workflow(wf_id, name, nodes, active=False):
    return [{"id": wf_id, "name": name, "active": active, "settings": {"executionOrder": "v1", "callerPolicy": "workflowsFromSameOwner"},
             "nodes": nodes, "connections": chain([n["name"] for n in nodes]), "pinData": {}, "tags": []}]


def tool(wf_id, name, files, call):
    nodes = [
        node(name, "When called", "n8n-nodes-base.executeWorkflowTrigger", 1.1, [0, 300], {"inputSource": "passthrough"}),
        node(name, "Read table", "n8n-nodes-base.readWriteFile", 1.1, [220, 300], {"operation": "read", "fileSelector": files, "options": {}},
             executeOnce=True),
        node(name, "Parse CSV", "n8n-nodes-base.extractFromFile", 1.1, [440, 300], {"operation": "csv", "options": {"includeEmptyCells": True}}),
        node(name, "Lookup", "n8n-nodes-base.code", 2, [660, 300], {"jsCode": LIB + "\n\n// ---- tool entry point (generated by scripts/workflows/build_tools.py)\n"
             "const input = $('When called').first().json;\n"
             "// body.query first: a webhook item also carries 'query' = its (empty) URL query string\n"
             "const query = (input.body && input.body.query) || input.query || input;\n"
             "const rows = $input.all().map(i => i.json);\n" + call}),
    ]
    return workflow(wf_id, name, nodes)


TOOLS = {
    "10_tool_lookup_exam": tool("cfToolExam000001", "10_tool_lookup_exam", "/data/tables/exam_calendar.csv",
                                "return [{ json: lookupExam(rows, query) }];"),
    "11_tool_lookup_contact": tool("cfToolContact001", "11_tool_lookup_contact", "/data/tables/directory.csv",
                                   "return [{ json: lookupContact(rows, query) }];"),
    "12_tool_lookup_request": tool("cfToolRequest001", "12_tool_lookup_request", "/data/tables/{request_catalogue,directory}.csv",
                                   "const req = rows.filter(r => r.request_id !== undefined), dir = rows.filter(r => r.role_id !== undefined);\n"
                                   "return [{ json: lookupRequest(req, dir, query) }];"),
}

CHECK = """// WF-2: the tools read these CSVs at every call; this report says whether they are usable right now
const rows = $input.all().map(i => i.json);
const spec = {
  exam_calendar: { id: 'exam_id', cols: ['exam_id','module_code','module_name','class_group','session','assessment','date','start_time','end_time','room','last_updated','data_status'], min: 30 },
  directory: { id: 'role_id', cols: ['role_id','role_title','email','office','reports_to'], min: 12 },
  request_catalogue: { id: 'request_id', cols: ['request_id','request_type','handler_role_id','required_documents','deadline_rule','regime','source'], min: 6 },
};
const report = [];
for (const [table, s] of Object.entries(spec)) {
  const t = rows.filter(r => r[s.id] !== undefined);
  const missingCols = t.length ? s.cols.filter(c => !(c in t[0])) : s.cols;
  const ids = t.map(r => r[s.id]);
  const dup = ids.filter((x, i) => ids.indexOf(x) !== i);
  const emptyId = t.filter(r => !r[s.id]).length;
  const badDate = table === 'exam_calendar' ? t.filter(r => !/^\\d{4}-\\d{2}-\\d{2}$/.test(r.date)).map(r => r.exam_id) : [];
  report.push({ table, rows: t.length, ok: !missingCols.length && !dup.length && !emptyId && !badDate.length && t.length >= s.min,
                missing_columns: missingCols, duplicate_ids: [...new Set(dup)], empty_ids: emptyId, invalid_dates: badDate.slice(0, 5),
                checked_at: new Date().toISOString() });
}
return report.map(r => ({ json: r }));"""

WF2 = workflow("cfWF2TablesChk1", "02_wf2_tables_check", [
    node("wf2", "Start (manual)", "n8n-nodes-base.manualTrigger", 1, [0, 300], {}),
    node("wf2", "Read tables", "n8n-nodes-base.readWriteFile", 1.1, [220, 300],
         {"operation": "read", "fileSelector": "/data/tables/{exam_calendar,directory,request_catalogue}.csv", "options": {}}, executeOnce=True),
    node("wf2", "Parse CSV", "n8n-nodes-base.extractFromFile", 1.1, [440, 300], {"operation": "csv", "options": {"includeEmptyCells": True}}),
    node("wf2", "Report", "n8n-nodes-base.code", 2, [660, 300], {"jsCode": CHECK}),
])

TEST = workflow("cfToolsTest00001", "03t_tools_test", [
    node("t", "Webhook", "n8n-nodes-base.webhook", 2.1, [0, 300],
         {"httpMethod": "POST", "path": "tools-test", "responseMode": "lastNode", "options": {}}, webhookId=nid("t", "hook")),
    node("t", "Call tool", "n8n-nodes-base.executeWorkflow", 1.2, [260, 300],
         {"source": "database", "workflowId": {"__rl": True, "mode": "id", "value": "={{ $json.body.workflow_id }}"},
          "mode": "once", "options": {"waitForSubWorkflow": True}}),
])


def main() -> None:
    for name, wf in {**TOOLS, "02_wf2_tables_check": WF2, "03t_tools_test": TEST}.items():
        (W / f"{name}.json").write_text(json.dumps(wf, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
        print(f"workflows/{name}.json")


if __name__ == "__main__":
    main()
