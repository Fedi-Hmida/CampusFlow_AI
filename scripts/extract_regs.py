CID = re.compile(r"\(cid:\d+\)")
FOOTER = re.compile(r"^ESPRIT-[A-Z]+-\d+\s*\|.*Page\s*\d+\s*$")
PAGENUM = re.compile(r"^\s*\d{1,3}\s*$")
TOC = re.compile(r"(\.{4,}|…{2,}|\s\d{1,2}\s*$)")
# a heading (Article / CHAPITRE / N.N / N-N) followed by dot leaders or a page number = table-of-contents line
TOC_LINE = re.compile(r"^\s*(Article\s*(\d+|premier|1er)|CHAPITRE\s+[IVXL]+|\d{1,2}\s*[.-]\s*\d{1,2})\s*:?\s*(.*?)\s*(\.{4,}|…{2,}|\s\d{1,3})\s*$", re.I)
ARTICLE = re.compile(r"^\s*Article\s*(\d+|premier|1er)\s*[:.–-]\s*(.*)$", re.I)
SUB = re.compile(r"^\s*(\d{1,2})\s*[-.]\s*(\d{1,2})\s*(?!%)([A-ZÉÈÀÂÎa-zé].*)$")  # "7-8Projet…" has no space in D1-003
CHAPTER = re.compile(r"^\s*CHAPITRE\s+([IVXL]+)\s*:?\s*(.*)$", re.I)
FICTIF_LABEL = "DOCUMENT FICTIF — projet CampusFlow AI, non officiel"  # header drawn by regenerate_fictif.py
MANUAL = ROOT / "scripts/manual_tables.json"  # hand-written serialisations (A6), keyed "<doc_id>/p<page>/t<index>"


def norm_ws(s: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", s)).strip()


def serialise(rows: list[list]) -> list[str]:
    rows = [[norm_ws(str(c or "")) for c in r] for r in rows if r and any(c for c in r)]
    if rows and len(rows[0]) == 2 and rows[0][0] in ("Référence", "Reference"):  # key/value header block of a procedure
        return [f"{k} : {v}" for k, v in rows]
    if len(rows) < 2:
        return [" ; ".join(c for c in r if c) for r in rows]
    head = [h or f"col{i + 1}" for i, h in enumerate(rows[0])]
    return ["; ".join(f"{h}: {v}" for h, v in zip(head, r) if v) for r in rows[1:]]


def page_lines(doc_id: str, page, manual: dict, toc_titles: dict) -> list[str]:
    """Text lines of one page in reading order, tables replaced by their serialisation."""
    tables = page.find_tables()
    boxes = [t.bbox for t in tables]
    items = []
    for ln in page.extract_text_lines():
        cy = (ln["top"] + ln["bottom"]) / 2
        if any(b[1] - 1 <= cy <= b[3] + 1 and b[0] - 1 <= ln["x0"] <= b[2] + 1 for b in boxes):
            continue
        items.append((ln["top"], ln["text"]))
    for i, t in enumerate(tables):
        key = f"{doc_id}/p{page.page_number}/t{i + 1}"
        rows = manual.get(key, {}).get("rows") or serialise(t.extract())
        tag = " (manual serialisation)" if key in manual else ""
        items.append((t.bbox[1], f"[Tableau p.{page.page_number}{tag}]"))
        items += [(t.bbox[1] + 0.01 * (j + 1), r) for j, r in enumerate(rows)]
    items.sort(key=lambda x: x[0])
    out = []
    for _, txt in items:
        txt = CID.sub("•", txt).strip()
        if not txt or txt == FICTIF_LABEL or FOOTER.match(txt) or PAGENUM.match(txt) or txt.upper() in ("SOMMAIRE", "TABLE DES MATIÈRES", "TABLE DES MATIERES"):
            continue
        m = TOC_LINE.match(txt)
        if m:
            if m.group(2):  # remember "Article N : title" from the TOC
                n = "1" if m.group(2).lower() in ("premier", "1er") else m.group(2)
                toc_titles.setdefault(n, norm_ws(re.sub(r"[.…]+$", "", m.group(3))))
            continue
        out.append(norm_ws(txt))
    return out


def split_units(doc_id: str, pages: list[list[str]], toc_titles: dict) -> list[dict]:
    units, cur, section, art_no = [], None, "", None

    def start(kind, number, title, page):
        nonlocal cur
        title = re.sub(r"\s*:?\s*$", "", norm_ws(title)) or "(sans titre)"
        cur = {"key": f"{doc_id}/{number}/{title}", "level": kind, "number": number, "title": title, "section": section,
               "page_start": page, "page_end": page, "lines": []}
        units.append(cur)

    for pno, lines in enumerate(pages, 1):
        for ln in lines:
            m_ch, m_art, m_sub = CHAPTER.match(ln), ARTICLE.match(ln), SUB.match(ln)
            is_toc = bool(TOC.search(ln)) and (m_ch or m_art or m_sub)
            if is_toc:
                continue
            if m_ch:
                section = norm_ws(f"CHAPITRE {m_ch.group(1)} : {m_ch.group(2)}").rstrip(" :")
                continue
            if m_art:
                art_no = "1" if m_art.group(1).lower() in ("premier", "1er") else m_art.group(1)
                title = m_art.group(2)
                if title.rstrip().endswith(".") or ". " in title or len(title) > 110:  # heading is a sentence, not a title
                    title = toc_titles.get(art_no, "(sans titre)")
                start("article", art_no, title, pno)
                cur["lines"].append(ln)
                continue
            if m_sub and art_no and m_sub.group(1) == art_no:
                start("subsection", f"{m_sub.group(1)}-{m_sub.group(2)}", m_sub.group(3), pno)
                cur["lines"].append(ln)
                continue
            if cur is None:
                start("preamble", "0", "Préambule", pno)
            cur["lines"].append(ln)
            cur["page_end"] = pno
    for u in units:
        u["text"] = "\n".join(u.pop("lines"))
        u["chars"] = len(norm_ws(u["text"]))
    return [u for u in units if u["chars"] > 0]


def strip_metadata(src: Path, dst: Path, title: str) -> None:
    r, w = PdfReader(str(src)), PdfWriter()
    for p in r.pages:
        w.add_page(p)
    w.add_metadata({"/Title": title, "/Producer": "CampusFlow AI scripts/extract_regs.py"})  # no /Author, /Creator
    with open(dst, "wb") as f:
        w.write(f)


def main() -> None:
    CLEAN.mkdir(parents=True, exist_ok=True)
    manual = json.loads(MANUAL.read_text(encoding="utf-8")) if MANUAL.exists() else {}
    for doc_id, raw, target, title, regime, status, source, date in DOCS:
        # FICTITIOUS documents are read from their regenerated, labelled copy (CF-104) once it exists
        src = OUT / target if status == "FICTITIOUS" and (OUT / target).exists() else RAW / raw
        with pdfplumber.open(str(src)) as pdf:
            toc_titles = {}
            pages = [page_lines(doc_id, p, manual, toc_titles) for p in pdf.pages]
        units = split_units(doc_id, pages, toc_titles)
        if status == "FICTITIOUS":  # every unit (future chunk) carries the label (A2)
            for u in units:
                u["text"] = f"[{FICTIF_LABEL}]\n" + u["text"]
        doc = {"doc_id": doc_id, "file": target, "raw_file": raw, "title": title, "regime": regime, "doc_status": status,
               "source": source, "source_pdf": str(src.relative_to(ROOT)).replace("\\", "/"), "date": date, "language": "fr", "n_pages": len(pages),
               "pages": [{"page": i + 1, "text": "\n".join(p)} for i, p in enumerate(pages)], "articles": units}
        (CLEAN / f"{doc_id}.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")
        if status == "official":
            strip_metadata(RAW / raw, OUT / target, title)
        arts = [u for u in units if u["level"] == "article"]
        subs = [u for u in units if u["level"] == "subsection"]
        print(f"{doc_id} {status:10} pages {len(pages):2} articles {len(arts):2} subsections {len(subs):2} units {len(units):2}")


if __name__ == "__main__":
    main()
